# -*- coding: utf-8 -*-
"""probe_textcf_haloquest.py -- per-token TEXT-channel counterfactual probe for
HaloQuest, paired with the existing image-swap probe
(outputs/claim_probe/haloquest_claim_probe_full.json, generated by
probe_claim_cf.py --dataset haloquest).

Design: on EXACTLY the same samples and the same teacher-forced token
positions as the existing claim probe (loaded from its saved `samples` list,
joined back to the scored file by id for token_ids), add a text-ablation view:

    full : own image + real question          (same as existing probe's full)
    noq  : own image + NEUTRAL question text  (question replaced by the
           placeholder "(no question provided)"; instruction line unchanged)

    delta_text_tok[i] = logP(tok_i | full) - logP(tok_i | noq)

The existing image-swap per-token delta (samples_meta['delta_tok']) is copied
through as delta_img_tok so (v, t) pairs are aligned row-by-row.

Resumable (skips ids already in the output file). Greedy n/a (no generation;
trajectory is the stored base greedy one, teacher-forced). Qwen2.5-Omni-7B.

    CUDA_VISIBLE_DEVICES=2 python probe_textcf_haloquest.py \
        --out outputs/cf_probe/haloquest_textcf_tokens.jsonl
"""
import os, sys, json, argparse, time

import numpy as np
import torch

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
sys.path.insert(0, os.path.join(HERE, 'OmniConfess', 'methods'))

os.environ.setdefault("MMHALU_MODEL_ROOT", "/ultrafast_share/tsq/MODELS")
os.environ.setdefault("PYTORCH_CUDA_ALLOC_CONF", "expandable_segments:True")

from shared import (  # noqa: E402
    load_dataset, load_media_for_item, resolve_media_path,
    load_model, build_inputs, prepare_for_thinker,
    build_user_content_with_media_tokens, make_messages,
    get_system_prompt, get_user_prompt,
)
from probe_claim_cf import view_logp, token_class  # noqa: E402

NEUTRAL_Q = "(no question provided)"


def neutralize_q(question, scheme, key):
    """Return the neutralized question text under the given scheme."""
    if scheme == 'placeholder':
        return NEUTRAL_Q
    if scheme == 'empty':
        return ''
    if scheme == 'shuffle':
        import hashlib, random
        words = question.split()
        if len(words) <= 1:
            return question
        seed = int(hashlib.sha256(str(key).encode('utf-8')).hexdigest(), 16) % (2 ** 31)
        r = random.Random(seed)
        w = list(words)
        while True:
            r.shuffle(w)
            if w != words:
                break
        return ' '.join(w)
    raise ValueError(scheme)


SRC_PROBE = os.path.join(HERE, 'outputs/claim_probe/haloquest_claim_probe_full.json')
SCORED = os.path.join(HERE, 'outputs/haloquest_base_model/'
                            'haloquest_base_model_full_single_scored.jsonl')


def build_view(processor, model, system_prompt, user_prompt, image):
    uc = build_user_content_with_media_tokens(None, None, image, user_prompt)
    messages = make_messages(system_prompt, uc)
    raw = build_inputs(processor, model, messages, None, None, image, 'haloquest')
    return prepare_for_thinker(raw, model)


def retry(fn, n=3, wait=5, tag=''):
    for i in range(n):
        try:
            return fn()
        except Exception as e:
            print(f'  [retry {i+1}/{n}] {tag}: {type(e).__name__}: {e}', flush=True)
            time.sleep(wait * (i + 1))
    raise RuntimeError(f'retries exhausted: {tag}')


def run(args):
    src = json.load(open(SRC_PROBE))
    meta = src['samples']
    print(f'[halo-textcf] {len(meta)} samples from {SRC_PROBE}', flush=True)

    scored = {r['id']: r for r in map(json.loads, open(SCORED))}
    data_path = os.path.join(HERE, 'OmniHalluBench', 'haloquest', 'haloquest.json')
    data_root = os.path.join(HERE, 'OmniHalluBench')
    data = load_dataset(data_path, data_root)
    by_id = {it['id']: it for it in data}

    done = set()
    if os.path.exists(args.out):
        for line in open(args.out):
            line = line.strip()
            if line:
                done.add(json.loads(line)['id'])
        print(f'[halo-textcf] resume: {len(done)} ids already done', flush=True)

    processor, model = load_model()
    tokenizer = processor.tokenizer
    thinker = model.thinker
    system_prompt = get_system_prompt('haloquest', 'v1')

    fout = open(args.out, 'a')
    t0 = time.time()
    n_new = 0
    for si, m in enumerate(meta if not args.limit else meta[:args.limit]):
        rid = m['id']
        if rid in done:
            continue
        rec = scored.get(rid)
        item = by_id.get(rid)
        if rec is None or item is None or not rec.get('token_ids'):
            continue
        try:
            img = load_media_for_item(item, data_path, data_root)[2]
            if img is None:
                continue
            gen_ids = torch.tensor(rec['token_ids'], dtype=torch.long,
                                   device=model.device)
            up_full = get_user_prompt(item['question'], 'haloquest', 'v1')
            up_noq = get_user_prompt(neutralize_q(item['question'], args.scheme, rid),
                                     'haloquest', 'v1')
            assert up_full != up_noq
            if args.scheme == 'placeholder':
                assert NEUTRAL_Q in up_noq

            views = {}
            for name, up in (('full', up_full), ('noq', up_noq)):
                v = retry(lambda u=up: build_view(processor, model, system_prompt, u, img),
                          tag=f'build_{name}')
                views[name] = retry(lambda vv=v: view_logp(thinker, vv, gen_ids),
                                    tag=f'forward_{name}')
                torch.cuda.empty_cache()

            d_text = views['full'] - views['noq']
            base_lp = np.array(rec['logp_list'], dtype=np.float64)
            repro = (float(np.max(np.abs(views['full'] - base_lp)))
                     if len(base_lp) == len(views['full']) else float('nan'))
            img_delta = np.asarray(m['delta_tok'], float)
            assert len(img_delta) == len(d_text), 'token alignment mismatch vs source probe'

            fout.write(json.dumps({
                'id': rid, 'n_tok': len(rec['token_ids']),
                'question': item['question'],
                'neg_item': m.get('neg_item'),
                'tokens': m['tokens'], 'classes': m['classes'],
                'delta_img_tok': m['delta_tok'],
                'lp_full': views['full'].round(4).tolist(),
                'lp_noq': views['noq'].round(4).tolist(),
                'delta_text_tok': d_text.round(4).tolist(),
                'scheme': args.scheme,
                'repro_err': round(repro, 4),
            }, ensure_ascii=False) + '\n')
            fout.flush()
            n_new += 1
        except Exception as e:
            print(f'[halo-textcf] id={rid} ERR {type(e).__name__}: {e}', flush=True)
            continue
        if (si + 1) % 10 == 0:
            print(f'[halo-textcf] {si+1}/{len(meta)} new={n_new} '
                  f'{(time.time()-t0)/max(n_new,1):.1f}s/new', flush=True)

    fout.close()
    n = sum(1 for _ in open(args.out))
    print(f'[halo-textcf] done -> {args.out} ({n} rows, {n_new} new)', flush=True)


if __name__ == '__main__':
    ap = argparse.ArgumentParser()
    ap.add_argument('--scheme', choices=['placeholder', 'shuffle', 'empty'],
                    default='placeholder')
    ap.add_argument('--limit', type=int, default=0)
    ap.add_argument('--out', default=os.path.join(
        HERE, 'outputs/cf_probe/haloquest_textcf_tokens.jsonl'))
    run(ap.parse_args())
