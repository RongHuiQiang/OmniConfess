#!/usr/bin/env python
# -*- coding: utf-8 -*-
"""A5 (ABLATION_PLAN.md): haloquest stratified ablation, missing cells.

Existing incremental chain (on disk): 34.22 base -> 35.41 +contract ->
39.87 +gate -> 40.06 +BoN -> 40.14 +feat-combo. Missing NON-NESTED combos
for the full 2^3 (contract x gate x BoN) table:

  cell_gate_bon (gate + BoN, NO contract): v1-prompt BoN pool (on disk for
      all 365, outputs/haloquest_bon_grounding) + gate routing
      (flagged -> T3 echo; non-flagged -> g_content-ranked BoN selection).
      ZERO GPU (all components on disk).
  cell_contract_bon (contract + BoN, NO gate): v2-contract BoN pool for all
      365 (81 already on disk from the stacked run; 284 generated by
      a5_contract_bon.py) -> same g_content selection, no routing.
      GPU.

Pre-registered judgement: with the full 2^3 table in hand, report whether
the incremental chain's ordering is preserved in non-nested combos; paired
Wilcoxon for each cell vs base and vs each single mechanism.
"""
import os
import sys
import json
import numpy as np
from scipy import stats

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from util import load_jsonl

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
os.chdir(ROOT)
sys.path.insert(0, ROOT)
sys.path.insert(0, os.path.join(ROOT, 'OmniConfess', 'methods'))

from answerability_gate import TEMPLATES, token_f1  # noqa: E402
from bon_grounding import rank_value  # noqa: E402

OUT = os.path.join(HERE, 'a5_gate_bon_cell.json')


def main():
    T3 = TEMPLATES['T3']
    bon = load_jsonl('outputs/haloquest_bon_grounding/haloquest_bon_grounding.jsonl')
    gate = {r['id']: r for r in load_jsonl(
        'outputs/answerability/haloquest_answerability_gate_full.jsonl')}
    base = {r['id']: r['eval_metrics']['Token-F1'] for r in load_jsonl(
        'outputs/haloquest_base_model/haloquest_base_model_full_single_scored.jsonl')}

    rows, rows_rand = [], []
    f1s, f1s_rand, f1s_base, f1s_gateonly, f1s_bononly = [], [], [], [], []
    gate_f1 = {r['id']: r['eval_metrics']['Token-F1'] for r in load_jsonl(
        'outputs/answerability/haloquest_answerability_gate_full_single_scored.jsonl')}
    for r in bon:
        i = r['id']
        g = gate.get(i)
        flagged = bool(g['flagged']) if g else False
        trajs = r.get('trajectories') or []
        if flagged:
            pred = T3(r['question'])
            pred_rand = pred
        else:
            sel = max(range(len(trajs)),
                      key=lambda k: rank_value(trajs[k]['grounding_scores'], 'g_content'))
            pred = trajs[sel]['pred']
            # random-selection control: the run's own stored random index
            ri = r.get('random_sel_rollout')
            ri = ri if (ri is not None and ri < len(trajs)) else 0
            pred_rand = trajs[ri]['pred']
        f1 = token_f1(pred, r['gt']) * 100
        f1r = token_f1(pred_rand, r['gt']) * 100
        rows.append(dict(id=i, question=r['question'], gt=r['gt'], flagged=flagged,
                         pred=pred, tf1=round(f1, 2), branch='T3' if flagged else 'bon_v1'))
        rows_rand.append(dict(id=i, gt=r['gt'], pred=pred_rand, tf1=round(f1r, 2)))
        f1s.append(f1)
        f1s_rand.append(f1r)
        if i in base:
            f1s_base.append(base[i])
        if i in gate_f1:
            f1s_gateonly.append(gate_f1[i])
        f1s_bononly.append(r['eval_metrics']['Token-F1'] if 'eval_metrics' in r else None)

    mean = lambda v: round(float(np.mean([x for x in v if x is not None])), 2)
    res = dict(
        cell='gate + BoN (no contract)',
        n=len(rows),
        tf1_cell=mean(f1s),
        tf1_random_sel=mean(f1s_rand),
        tf1_base=mean(f1s_base),
        tf1_gate_only=mean(f1s_gateonly),
        d_vs_base=round(mean(f1s) - mean(f1s_base), 2),
        p_vs_base=float(stats.wilcoxon([a - b for a, b in zip(f1s, f1s_base)]).pvalue),
        d_vs_gate_only=round(mean(f1s) - mean(f1s_gateonly), 2),
        p_vs_gate_only=float(stats.wilcoxon([a - b for a, b in zip(f1s, f1s_gateonly)]).pvalue),
        d_vs_random_sel=round(mean(f1s) - mean(f1s_rand), 2),
        p_vs_random_sel=float(stats.wilcoxon([a - b for a, b in zip(f1s, f1s_rand)]).pvalue),
        flagged_n=sum(1 for r in rows if r['flagged']),
        note='selection = g_content rank on the v1-pool BoN candidates (on-disk '
             'rollouts), gate flags from the shipped gate run; zero new forwards')
    with open('outputs/haloquest_a5/haloquest_a5_gate_bon.jsonl', 'w') as f:
        for r in rows:
            f.write(json.dumps(r, ensure_ascii=False) + '\n')
    with open(OUT, 'w') as f:
        json.dump(res, f, ensure_ascii=False, indent=1)
    print(json.dumps(res, ensure_ascii=False, indent=1))


if __name__ == '__main__':
    main()
